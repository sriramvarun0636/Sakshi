"""Render the data-preparation statistics (JSON written by the pipeline) as Markdown tables."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


def _load(report_dir: Path, name: str) -> Any:
    p = report_dir / name
    return json.loads(p.read_text()) if p.exists() else None


def _table(rows: list[list[Any]], header: list[str]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def _pct(a: float, b: float) -> str:
    return f"{a / b:.0%}" if b else "n/a"


def write_tables(report_dir: Path) -> Path:
    """Regenerate `tables.md` in `report_dir` from the pipeline's JSON outputs."""
    ms = _load(report_dir, "manifest_stats.json") or {}
    cal = _load(report_dir, "phash_calibration.json")
    dd = _load(report_dir, "dedupe_stats.json")
    au = _load(report_dir, "cib_disaster_type_audit.json")
    sp = _load(report_dir, "split_summary.json")
    out = [
        "# Data preparation: generated tables",
        "",
        "Generated by `sakshi-data prepare`; do not edit by hand. Interpretation: [README.md](README.md).",
        "",
    ]

    c = ms.get("crisismmd", {})
    out += ["## CrisisMMD", "", _table([[k, v] for k, v in c.items()], ["check", "value"]), ""]

    if "cib" in ms:
        m = ms["cib"]
        present = m["files_present_by_source"]
        out += [
            "## Crisis Image Benchmark (AIDR-DT + DMD)",
            "",
            f"{m['images_labelled']:,} labelled images; {m['images_with_files']:,} have image files.",
            "",
            _table([[k, v, present.get(k, 0)] for k, v in m["by_source"].items()], ["source", "labelled", "with files"]),
            "",
            _table([[k, v] for k, v in m["labelled"].items()], ["label", "images labelled"]),
            "",
            _table(
                [[k, v] for k, v in m["mapped_to_crisismmd_event"].items()], ["AIDR folder mapped to CrisisMMD event", "images"]
            ),
            "",
            "Images whose disaster-type and severity official splits disagree: "
            f"{m['images_with_conflicting_official_splits']:,}.",
            "",
        ]
    else:
        out += ["## Crisis Image Benchmark", "", "Not present; the sections below cover CrisisMMD only.", ""]

    if "humaid" in ms:
        hm = ms["humaid"]
        out += [
            "## HumAID",
            "",
            f"{hm['tweets']:,} tweets from {hm['events']} events. Same tweet id as a CrisisMMD tweet: "
            f"{hm['same_tweet_id_as_crisismmd']}; same normalised text: {hm['same_normalised_text_as_crisismmd']}. "
            f"{hm['excluded_from_humaid_evaluation']} tweets are excluded from HumAID evaluation "
            "(`data/processed/humaid_exclude.csv`).",
            "",
        ]

    if cal:
        fit = cal["tail_fit"]
        rows = [[t, r["linked"], r["expected_chance"], r["est_precision"]] for t, r in cal["cumulative"].items()]
        out += [
            "## pHash threshold calibration",
            "",
            f"Distances between {cal['random_pairs_sampled']:,} random image pairs were fitted on {fit['distances']} "
            f"(each 2 bits closer is {fit['ratio_per_2_bits']}× as likely) and extrapolated downwards to estimate "
            "how many linked pairs are chance collisions between unrelated images.",
            "",
            _table(rows, ["distance ≤", "linked pairs", "expected chance pairs", "est. precision"]),
            "",
        ]

    if dd:
        rows = [[k, v] for k, v in dd.items() if k not in ("threshold", "distance_histogram")]
        out += [f"## Near-duplicates at distance ≤ {dd['threshold']}", "", _table(rows, ["", "pairs"]), ""]

    if au:
        out += [
            "## Disaster-type label audit",
            "",
            f"Image-weighted purity of {au['aidr_single_event_folders']} single-event AIDR-DT folders: "
            f"**{au['aidr_weighted_folder_purity']}** (≥ 0.9 would indicate labels read off the folder). "
            f"Folder-derived: **{au['folder_derived']}**.",
            "",
            _table([[f, v] for f, v in au["folder_purity"].items()], ["AIDR-DT folder", "purity"]),
            "",
            _table([[f, v] for f, v in au["crisismmd_event_folders"].items()], ["folder (a CrisisMMD event)", "labels"]),
            "",
            _table(
                [[f, v] for f, v in au["dmd_folder_vs_type"].items()], ["DMD folder (DMD damage class)", "disaster-type labels"]
            ),
            "",
        ]
        if "crisismmd_cross_check" in au:
            x = au["crisismmd_cross_check"]
            classes = sorted({k for d in x["crosstab"].values() for k in d})
            rows = [[t, *[x["crosstab"][t].get(k, 0) for k in classes]] for t in x["crosstab"]]
            out += [
                f"Cross-check on {x['linked_pairs']} image pairs linking the benchmark to CrisisMMD:",
                "",
                _table(rows, ["CIB disaster type", *[f"CrisisMMD {k}" for k in classes]]),
                "",
            ]

    if sp:
        rows = [
            [
                src,
                v["official_train"],
                v["kept_as_train"],
                _pct(v["kept_as_train"], v["official_train"]),
                f"{v['official_test_kept_as_test']}/{v['official_test']}",
            ]
            for src, v in sp["per_source"].items()
            if v["official_train"]
        ]
        out += [
            "## Unified split",
            "",
            _table([[k, v] for k, v in sp["resolved"].items()], ["split", "images"]),
            "",
            _table(rows, ["official split", "official train", "still train", "kept", "official test still test"]),
            "",
            f"Linked groups: {sp['components']:,}; largest {sp['largest_component']}; "
            f"{sp['components_over_10']} with more than 10 members; {sp['components_spanning_datasets']} span both datasets.",
            "",
            f"Linked pairs (exact copies and near-duplicates): {sp['linked_pairs']:,}, of which "
            f"{sp['linked_pairs_straddling_official_train_test']:,} straddle the official train/test boundary.",
            "",
            "### Labels per split",
            "",
        ]
        for col, tab in sp["labels_by_split"].items():
            classes = sorted({k for d in tab.values() for k in d})
            order = [x for x in ("train", "dev", "test") if x in tab]
            rows = [[k, *[tab[s].get(k, 0) for s in order]] for k in classes]
            out += [f"**{col}**", "", _table(rows, ["class", *order]), ""]
        roles = ["train", "dev", "test", "excluded"]
        rows = [[f.removeprefix("loeo_"), *[v.get(r, 0) for r in roles]] for f, v in sp["loeo"].items()]
        out += ["### Leave-one-event-out folds", "", _table(rows, ["held-out event", *roles]), ""]

    path = report_dir / "tables.md"
    path.write_text("\n".join(out))
    return path
